#!/usr/bin/env node
/**
 * Free LinkedIn → portfolio sync.
 *
 * Default (free): reads content/linkedin/profile.json and writes
 * src/lib/linkedin-generated.ts which data.ts can import.
 *
 * Optional paid API (NOT free): set LINKEDIN_API_KEY + --provider=proxycurl
 * Official LinkedIn Profile API is not available as a free personal sync.
 *
 * Usage:
 *   npm run sync:linkedin
 *   npm run sync:linkedin -- --dry-run
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const profilePath = path.join(root, "content/linkedin/profile.json");
const outPath = path.join(root, "src/lib/linkedin-generated.ts");

const args = new Set(process.argv.slice(2));
const dryRun = args.has("--dry-run");
const provider = (() => {
  const i = process.argv.indexOf("--provider");
  return i >= 0 ? process.argv[i + 1] : "local";
})();

function fail(msg) {
  console.error(`ERROR: ${msg}`);
  process.exit(1);
}

async function loadProfile() {
  if (provider === "proxycurl") {
    const key = process.env.LINKEDIN_API_KEY;
    const url =
      process.env.LINKEDIN_PROFILE_URL ||
      "https://www.linkedin.com/in/iftekhareather/";
    if (!key) {
      fail(
        "Proxycurl requires LINKEDIN_API_KEY (paid). Use free local JSON instead: npm run sync:linkedin"
      );
    }
    console.log("==> Fetching via Proxycurl (paid API)...");
    const endpoint = `https://nubela.co/proxycurl/api/v2/linkedin?url=${encodeURIComponent(url)}`;
    const res = await fetch(endpoint, {
      headers: { Authorization: `Bearer ${key}` },
    });
    if (!res.ok) {
      fail(`Proxycurl HTTP ${res.status}: ${await res.text()}`);
    }
    const remote = await res.json();
    // Map a few fields; keep structure compatible with local JSON
    return {
      updatedAt: new Date().toISOString().slice(0, 10),
      source: `Proxycurl · ${url}`,
      siteConfig: {
        title: remote.headline || "",
        tagline: remote.headline || "",
        summary: remote.summary || "",
        location: [remote.city, remote.state, remote.country_full_name]
          .filter(Boolean)
          .join(", "),
      },
      focusAreas: (remote.skills || []).slice(0, 8).map((s) => s.name || s),
      recommendations: (remote.recommendations || []).slice(0, 4).map((r) => ({
        name: r.recommender?.name || "Colleague",
        title: r.recommender?.title || "LinkedIn recommendation",
        quote: r.recommendation_text || "",
        linkedin: r.recommender?.linkedin_profile_url || url,
      })),
      skills: [],
      stats: [],
      notes: ["Merged from Proxycurl - review before deploy."],
    };
  }

  if (!fs.existsSync(profilePath)) {
    fail(`Missing ${profilePath}`);
  }
  console.log("==> Reading free local profile:", path.relative(root, profilePath));
  return JSON.parse(fs.readFileSync(profilePath, "utf8"));
}

function toTs(profile) {
  const payload = {
    updatedAt: profile.updatedAt ?? new Date().toISOString().slice(0, 10),
    source: profile.source ?? "local",
    siteConfig: profile.siteConfig ?? {},
    focusAreas: profile.focusAreas ?? [],
    stats: profile.stats ?? [],
    skills: profile.skills ?? [],
    recommendations: profile.recommendations ?? [],
  };

  return `/* eslint-disable */
/**
 * AUTO-GENERATED by scripts/sync-linkedin-profile.mjs
 * Do not edit by hand - update content/linkedin/profile.json and run:
 *   npm run sync:linkedin
 *
 * Source: ${payload.source}
 * Updated: ${payload.updatedAt}
 */
export const linkedInGenerated = ${JSON.stringify(payload, null, 2)} as {
  updatedAt: string;
  source: string;
  siteConfig: {
    title: string;
    tagline: string;
    summary: string;
    location: string;
  };
  focusAreas: string[];
  stats: { label: string; value: string }[];
  skills: { category: string; items: string[] }[];
  recommendations: {
    name: string;
    title: string;
    quote: string;
    linkedin: string;
  }[];
};

export type LinkedInGenerated = typeof linkedInGenerated;
`;
}

async function main() {
  console.log("LinkedIn sync (free local JSON by default)");
  console.log("  Provider:", provider);
  if (provider !== "local" && provider !== "proxycurl") {
    fail(`Unknown provider "${provider}". Use local or proxycurl.`);
  }

  const profile = await loadProfile();
  const ts = toTs(profile);

  if (dryRun) {
    console.log("\n--dry-run - would write:\n");
    console.log(ts.slice(0, 800) + "\n…");
    return;
  }

  fs.writeFileSync(outPath, ts, "utf8");
  console.log("==> Wrote", path.relative(root, outPath));
  console.log("");
  console.log("Next:");
  console.log("  1. Review src/lib/linkedin-generated.ts");
  console.log("  2. If Admin → Settings overrides title/summary in DB, update those in Admin too");
  console.log("  3. Commit when ready");
  console.log("");
  console.log("Note: Official LinkedIn Profile API is NOT free for personal portfolio sync.");
  console.log("      Paid Proxycurl optional: LINKEDIN_API_KEY=… npm run sync:linkedin -- --provider=proxycurl");
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
